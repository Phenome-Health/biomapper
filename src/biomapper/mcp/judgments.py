"""Agent suggestions on weak refs (1.7.0, v1: suggestions only).

``record_suggestion(ref, choice, rationale)`` stores the agent's pick for one weak ref. The choice
must come from that ref's latest USABLE candidate set (a ``present`` fetch), or be the engine's
own choice, or ``none``. A ``run_mismatch`` set never backs a suggestion. A suggestion is an
agent's opinion, never a BioMapper resolution and never a human judgment: it reaches no main
output, only the job's server-owned ``choices.tsv`` sidecar.

Storage is one private file per record next to the ref (``.../judgments/<ref>/``), so interactive
suggestions share the ref's 30-day TTL and job suggestions share the job's lifecycle. One
suggestion per ref is current; re-recording writes a new record and marks the old one superseded,
so history is kept.
"""

from __future__ import annotations

import secrets
import time
from collections.abc import Callable
from typing import Literal

from pydantic import BaseModel, Field

from biomapper.mcp._storage import private_dir, utc, write_private
from biomapper.mcp.candidates import _norm_curie, sanitize
from biomapper.mcp.references import (
    CandidateSet,
    RefEngine,
    RefPins,
    RefQuery,
    RefRecord,
    RefStore,
)

MAX_RATIONALE = 500
NONE_CHOICE = "none"

ChoiceSource = Literal["candidate", "engine", "none", "link"]
# 1.9.0: what an agent may suggest for a LINK review item of a harmonize job.
LINK_CHOICES: tuple[str, ...] = ("same", "different", "cannot_tell")

CHOICES_MARKER = (
    "# biomapper choices.tsv v1: server-owned, regenerated by record_suggestion. Agent "
    "suggestions, NOT BioMapper resolutions or human judgments. Do not edit."
)
CHOICES_COLUMNS = [
    "key", "name", "ref", "weak_trigger", "engine_choice", "certificate_state",
    "suggested_choice", "choice_source", "rationale", "recorded_utc",
]

SUGGESTION_NOTE = (
    "Recorded as an agent suggestion: not a BioMapper resolution and not a human judgment. The "
    "engine's choice and the main output are unchanged."
)

RECORD_SUGGESTION_DESCRIPTION = (
    "Record your suggested answer for ONE weak ref: a CURIE from that ref's latest "
    "get_candidates result, the engine's own choice, or 'none' (no candidate fits). rationale is "
    "a short reason (capped at 500 characters). This is an agent suggestion, not a BioMapper "
    "resolution: it never changes the engine's choice or the main output. Recording again on "
    "the same ref replaces the current suggestion and keeps the history. For map_file refs it "
    "also rewrites the server-owned <output>.choices.tsv. For a harmonize job's review items "
    "(list_review_items) it rewrites choices.tsv in the job's output_dir: a row item takes a "
    "CURIE, the engine's choice or 'none' as above; a LINK item takes 'same', 'different' or "
    "'cannot_tell' (are the two sides the same entity?). Never describe a suggestion as "
    "BioMapper's resolution or as a person's judgment."
)


class JudgmentError(Exception):
    """A suggestion the server refuses; the message tells the agent what would be accepted."""


class Suggestion(BaseModel):
    suggestion_id: str
    kind: Literal["agent_suggestion"] = "agent_suggestion"
    ref: str
    choice: str
    choice_source: ChoiceSource
    rationale: str
    recorded_utc: str
    recorded_ts: float
    candidate_set_fetched_utc: str | None = None
    candidate_set_n: int | None = None
    query: RefQuery
    engine: RefEngine
    weak_trigger: str | None = None
    pins: RefPins
    source: str
    job_id: str | None = None
    row_key: str | None = None
    supersedes: str | None = None
    superseded_by: str | None = None


class LinkSuggestion(BaseModel):
    """An agent's same / different / cannot_tell on one link review item (1.9.0)."""

    suggestion_id: str
    kind: Literal["agent_link_suggestion"] = "agent_link_suggestion"
    ref: str
    job_id: str
    choice: str
    rationale: str
    recorded_utc: str
    recorded_ts: float
    nodes: list[str | None] = Field(default_factory=list)
    labels: list[str] = Field(default_factory=list)
    reasons: list[str] = Field(default_factory=list)
    supersedes: str | None = None
    superseded_by: str | None = None


def validate_link_choice(choice: str) -> str:
    """``same``, ``different`` or ``cannot_tell`` (spaces and hyphens accepted); else an error."""
    value = "_".join((choice or "").strip().lower().replace("-", " ").split())
    if value in ("cant_tell", "can't_tell", "unsure", "unknown"):
        value = "cannot_tell"
    if value not in LINK_CHOICES:
        raise JudgmentError(
            f"{(choice or '')[:60]!r} is not an answer for a link review item. A link asks "
            "whether its two sides are the same entity: suggest same, different or cannot_tell."
        )
    return value


class SuggestionResult(BaseModel):
    suggestion_id: str
    ref: str
    choice: str
    choice_source: ChoiceSource
    supersedes: str | None = None
    recorded_utc: str
    choices_path: str | None = Field(
        default=None, description="The job's choices.tsv, for map_file and harmonize job refs"
    )
    note: str = SUGGESTION_NOTE


def latest_usable_set(record: RefRecord) -> CandidateSet:
    """The newest ``present`` candidate set on the ref, or :class:`JudgmentError` saying why not.

    A later failed or empty fetch does not erase an earlier usable set. A ``run_mismatch`` does:
    the engine's answer moved, so every older set on this ref is stale.
    """
    sets = [*([record.candidates] if record.candidates else []),
            *reversed(record.candidate_history)]
    if not sets:
        raise JudgmentError(
            f"No candidates have been fetched for {record.ref_id}. Call get_candidates first, or "
            f"suggest the engine's choice ({record.engine_choice or 'none'}) or 'none'."
        )
    for stored in sets:
        if stored.status == "run_mismatch":
            successor = record.superseded_by or "the superseding_ref get_candidates returned"
            raise JudgmentError(
                f"{record.ref_id} has no usable candidate set: its latest re-map was a "
                f"run_mismatch ({stored.reason}). Record the suggestion on {successor}."
            )
        if stored.usable:
            return stored
    latest = sets[0]
    raise JudgmentError(
        f"{record.ref_id} has no usable candidate set (latest fetch: {latest.status}"
        f"{', ' + latest.reason if latest.reason else ''}). Fetch candidates again, or suggest "
        f"the engine's choice or 'none'."
    )


def validate_choice(
    record: RefRecord, choice: str
) -> tuple[str, ChoiceSource, CandidateSet | None]:
    """The canonical choice, where it came from, and the set backing it; or JudgmentError."""
    value = (choice or "").strip()
    if value.lower() == NONE_CHOICE:
        return NONE_CHOICE, "none", None
    key = _norm_curie(value)
    engine = {_norm_curie(c): c for c in (record.engine.chosen_kg_id, record.engine.primary_curie)
              if c}
    if key in engine:
        return engine[key], "engine", None
    stored = latest_usable_set(record)
    for item in stored.items:
        if _norm_curie(item.curie) == key:
            return item.curie, "candidate", stored
    raise JudgmentError(
        f"{value!r} is not in the candidates last fetched for {record.ref_id}, and is not the "
        f"engine's choice. Suggest one of those CURIEs, or 'none'."
    )


class SuggestionStore:
    """One file per suggestion, next to its ref."""

    def __init__(self, refs: RefStore, *, wall_clock: Callable[[], float] = time.time) -> None:
        self.refs = refs
        self._clock = wall_clock

    def history(self, ref_id: str) -> list[Suggestion]:
        directory = self.refs.judgments_dir(ref_id)
        if not directory.is_dir():
            return []
        out: list[Suggestion] = []
        for path in sorted(directory.glob("sugg-*.json")):
            try:
                out.append(Suggestion.model_validate_json(path.read_text(encoding="utf-8")))
            except (OSError, ValueError):
                continue
        out.sort(key=lambda s: (s.recorded_ts, s.suggestion_id))
        return out

    def current(self, ref_id: str) -> Suggestion | None:
        live = [s for s in self.history(ref_id) if s.superseded_by is None]
        return live[-1] if live else None

    def record(
        self,
        record: RefRecord,
        choice: str,
        source: ChoiceSource,
        rationale: str,
        stored: CandidateSet | None = None,
    ) -> Suggestion:
        now = self._clock()
        previous = self.current(record.ref_id)
        suggestion = Suggestion(
            suggestion_id=f"sugg-{int(now * 1e6):016d}-{secrets.token_hex(6)}",
            ref=record.ref_id,
            choice=choice,
            choice_source=source,
            rationale=sanitize(rationale, MAX_RATIONALE),
            recorded_utc=utc(now),
            recorded_ts=now,
            candidate_set_fetched_utc=stored.fetched_utc if stored else None,
            candidate_set_n=stored.n if stored else None,
            query=record.query,
            engine=record.engine,
            weak_trigger=record.weak_trigger,
            pins=record.pins,
            source=record.source,
            job_id=record.job_id,
            row_key=record.row_key,
            supersedes=previous.suggestion_id if previous else None,
        )
        directory = self.refs.judgments_dir(record.ref_id)
        private_dir(directory.parent)
        private_dir(directory)
        write_private(directory / f"{suggestion.suggestion_id}.json",
                      suggestion.model_dump_json(indent=2))
        if previous is not None:
            previous.superseded_by = suggestion.suggestion_id
            write_private(directory / f"{previous.suggestion_id}.json",
                          previous.model_dump_json(indent=2))
        return suggestion

    # -- link review items (1.9.0) -------------------------------------------

    def link_history(self, ref_id: str) -> list[LinkSuggestion]:
        directory = self.refs.judgments_dir(ref_id)
        if not directory.is_dir():
            return []
        out: list[LinkSuggestion] = []
        for path in sorted(directory.glob("sugg-*.json")):
            try:
                out.append(LinkSuggestion.model_validate_json(path.read_text(encoding="utf-8")))
            except (OSError, ValueError):
                continue
        out.sort(key=lambda s: (s.recorded_ts, s.suggestion_id))
        return out

    def current_link(self, ref_id: str) -> LinkSuggestion | None:
        live = [s for s in self.link_history(ref_id) if s.superseded_by is None]
        return live[-1] if live else None

    def record_link(
        self,
        ref_id: str,
        job_id: str,
        choice: str,
        rationale: str,
        *,
        nodes: list[str | None],
        labels: list[str],
        reasons: list[str],
    ) -> LinkSuggestion:
        now = self._clock()
        previous = self.current_link(ref_id)
        suggestion = LinkSuggestion(
            suggestion_id=f"sugg-{int(now * 1e6):016d}-{secrets.token_hex(6)}",
            ref=ref_id,
            job_id=job_id,
            choice=choice,
            rationale=sanitize(rationale, MAX_RATIONALE),
            recorded_utc=utc(now),
            recorded_ts=now,
            nodes=list(nodes),
            labels=[sanitize(x) for x in labels],
            reasons=list(reasons),
            supersedes=previous.suggestion_id if previous else None,
        )
        directory = self.refs.judgments_dir(ref_id)
        private_dir(directory.parent.parent)
        private_dir(directory.parent)
        private_dir(directory)
        write_private(directory / f"{suggestion.suggestion_id}.json",
                      suggestion.model_dump_json(indent=2))
        if previous is not None:
            previous.superseded_by = suggestion.suggestion_id
            write_private(directory / f"{previous.suggestion_id}.json",
                          previous.model_dump_json(indent=2))
        return suggestion

    def link_rows(self, link_refs: list[str]) -> list[list[object]]:
        """``choices.tsv`` rows for the link items of one harmonize job, in the order given."""
        rows: list[list[object]] = []
        for ref_id in link_refs:
            current = self.current_link(ref_id)
            if current is None:
                continue
            rows.append([
                "", " | ".join(current.labels), ref_id, "link",
                " | ".join(n or "" for n in current.nodes), "", current.choice, "link",
                current.rationale, current.recorded_utc,
            ])
        return rows

    def job_rows(self, job_id: str) -> list[list[object]]:
        """``choices.tsv`` rows: the current suggestion of every ref of one job."""
        refs_dir = self.refs.jobs_dir / job_id / "refs"
        rows: list[tuple[tuple[int, str], list[object]]] = []
        if not refs_dir.is_dir():
            return []
        for path in refs_dir.glob("jref-*.json"):
            ref_id = path.name[: -len(".json")]
            current = self.current(ref_id)
            if current is None:
                continue
            key = current.row_key or ""
            order = (int(key), key) if key.isdigit() else (1 << 62, key)
            rows.append((order, [
                key, current.query.name, ref_id, current.weak_trigger or "",
                current.engine.chosen_kg_id or current.engine.primary_curie or "",
                current.engine.certificate_state or "", current.choice, current.choice_source,
                current.rationale, current.recorded_utc,
            ]))
        rows.sort(key=lambda r: (r[0], str(r[1][2])))
        return [r for _, r in rows]
